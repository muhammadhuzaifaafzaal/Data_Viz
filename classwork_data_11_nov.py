import pandas as pd
import folium
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np

# Read and fetch file, skipping the metadata rows
De = pd.read_excel('/content/ghgp_data_by_year_2023.xlsx', sheet_name='LDC - Direct Emissions', skiprows=3)

# Describe the cleaned dataset
display(De.describe())
De.info()

# Fill missing numeric values with column means
De_filled = De.fillna(De.mean(numeric_only=True))

# Convert to numpy array correctly
GHG_ARRAY = De_filled.to_numpy()

# Emissions columns are at indices 13 through 25
emissions_only = GHG_ARRAY[:, 13:].astype(float)

# Sum down columns ignoring missing values (using filled data)
column_sums = np.sum(emissions_only, axis=0)

# Check for any remaining missing values
print("Missing values sum:\n", np.sum(De_filled.isna()))

# Define the years in chronological order (columns 13 to 25 are 2023 down to 2011, so we reverse them for chronological trend)
years = np.array([2011, 2012, 2013, 2014, 2015, 2016, 2017, 2018, 2019, 2020, 2021, 2022, 2023])
total_emissions_chrono = column_sums[::-1]

# Create the trend line
plt.figure(figsize=(10, 6))
plt.plot(years, total_emissions_chrono, marker='o', color='b', linestyle='-', linewidth=2)
plt.title('Trend Line of Total Direct Emissions Over Years (LDC)')
plt.xlabel('Year')
plt.ylabel('Total Direct Emissions (Metric Tons CO2e)')
plt.grid(True, linestyle='--', alpha=0.7)
plt.xticks(years)
plt.tight_layout()
plt.show()